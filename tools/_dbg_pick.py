"""'候选1和候选3不要' — 候选1 后面跟'和'没命中 post-neg (要求紧邻不要).
放宽: post-neg 改为 候选N[和候选M]*不要 枚举串. 或更简单: _ORD_NEG_RE 本身支持
'候选1和候选3不要' — 把 post-neg 扩成 (候选N\s*(?:和\s*)?)+不要 形式."""
import re
utt = '候选1和候选3不要，要候选2。'
# 枚举串: (候选|第N条) 出现至少2次后跟不要
m = re.findall(r'候选\s*([一二三四五六七八九十\d]+)(?=[和,，、\s]*候选|[和,，、\s]*不要|不要)', utt)
print('enum finds:', m)
